function normalizeSearchString(text: string): string {
  return text
    .toLowerCase()
    .trim()
    .replace(/[أإآ]/g, 'ا')
    .replace(/[ة]/g, 'ه')
    .replace(/[ى]/g, 'ي')
    .replace(/[\u064B-\u065F]/g, ''); // Remove Arabic tashkeel / diacritics
}

export function searchCatalog(filter: CatalogSearchFilter): CatalogExercise[] {
  const { query, muscleGroup, equipment } = filter;
  const cleanQuery = query ? normalizeSearchString(query) : '';

  return EXERCISE_CATALOG.filter((ex) => {
    // 1. Muscle group filter
    if (muscleGroup && muscleGroup !== 'all') {
      const matchesMuscle =
        ex.primaryMuscle === muscleGroup || ex.secondaryMuscles.includes(muscleGroup);
      if (!matchesMuscle) return false;
    }

    // 2. Equipment filter
    if (equipment && equipment !== 'all') {
      if (ex.equipment !== equipment) return false;
    }

    // 3. Search query
    if (!cleanQuery) return true;

    const nameEnNorm = normalizeSearchString(ex.nameEn);
    const nameArNorm = normalizeSearchString(ex.nameAr);
    if (nameEnNorm.includes(cleanQuery) || nameArNorm.includes(cleanQuery)) {
      return true;
    }

    const aliasEnMatch = ex.aliasesEn.some((a) => normalizeSearchString(a).includes(cleanQuery));
    if (aliasEnMatch) return true;

    const aliasArMatch = ex.aliasesAr.some((a) => normalizeSearchString(a).includes(cleanQuery));
    if (aliasArMatch) return true;

    return false;
  });
}
